    @MainActor private static var cache: [String: NSImage] = [:]

    @MainActor
    static func image(_ drill: Drill, frame: Int) -> NSImage {
        let grids = frames[drill] ?? []
        guard !grids.isEmpty else { return NSImage() }
        let index = abs(frame) % grids.count
        let key = "\(drill)-\(index)"
        if let cached = cache[key] { return cached }

        let grid = grids[index]
        let cell: CGFloat = 1.5
        let size = NSSize(width: 12 * cell, height: 12 * cell)
        let image = NSImage(size: size, flipped: true) { _ in
            NSColor.black.setFill()
            for (row, line) in grid.enumerated() {
                for (column, character) in line.enumerated() where character == "#" {
                    NSRect(x: CGFloat(column) * cell, y: CGFloat(row) * cell, width: cell, height: cell).fill()
                }
            }
            return true
        }
        // 템플릿 이미지로 두면 상단바 색(밝은·어두운 모드)에 맞춰 칠해진다.
        image.isTemplate = true
        cache[key] = image
        return image
    }
